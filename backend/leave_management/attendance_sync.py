
from datetime import timedelta

from django.db import transaction

from attendance.models import Attendance


class AttendanceConflictError(Exception):
    pass


@transaction.atomic
def create_leave_attendance(leave):
    """
    Create LEAVE attendance for every approved leave date.
    Never overwrite manually entered attendance.
    """

    current_date = leave.start_date

    while current_date <= leave.end_date:

        existing = Attendance.objects.select_for_update().filter(
            employee=leave.employee,
            date=current_date
        ).first()

        if existing:
            if (
                existing.leave_request_id == leave.id
                and existing.status == "LEAVE"
            ):
                current_date += timedelta(days=1)
                continue

            raise AttendanceConflictError(
                f"Attendance already exists for {current_date}. "
                "Resolve the existing attendance before approving leave."
            )

        Attendance.objects.create(
            employee=leave.employee,
            date=current_date,
            status="LEAVE",
            leave_request=leave
        )

        current_date += timedelta(days=1)


@transaction.atomic
def remove_leave_attendance(leave):
    """
    Remove only attendance generated by this leave request.
    Preserve manually created attendance records.
    """

    Attendance.objects.filter(
        leave_request=leave,
        employee=leave.employee,
        status="LEAVE"
    ).delete()
